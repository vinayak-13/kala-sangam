export function getProductById(id: string): CatalogProductItem | undefined {
  return CRAFT_CATALOG.find((p) => p.id === id);
}

export function getArtisanByHandle(handle: string): CraftArtisan | undefined {
  const clean = handle.replace(/^@/, '').toLowerCase();
  const prod = CRAFT_CATALOG.find((p) => p.artisan.handle.toLowerCase() === clean);
  return prod?.artisan;
}
